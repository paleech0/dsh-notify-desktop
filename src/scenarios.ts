/**
 * The notification situations, shared by both halves of the plugin.
 *
 * A "scenario" is one event that can raise a notification: the five ways a turn
 * can end, the three blocking interactions, and the reminder for a wait that is
 * still unanswered. Each scenario carries its own sound and its own popup-text
 * choice, and owns a small library of named custom texts (at most
 * {@link TEXT_LIMIT_PER_SCENARIO}).
 *
 * The host validates text templates against this list; the client keys its
 * sound map, its text map and the settings UI by it. It lives outside
 * `types.ts` so the host bundle can pull it in without the client's preference
 * shapes.
 */

/** Every notifiable situation, in the order the settings page lists them. */
export const SCENARIO_IDS = Object.freeze([
  'completed',
  'error',
  'aborted',
  'blocked',
  'max-tokens',
  'approval',
  'question',
  'plan-review',
  'reminder',
] as const)

/** One notifiable situation. */
export type NotifyScenario = (typeof SCENARIO_IDS)[number]

/** The situations caused by a turn ending, in settings order. */
export const TURN_SCENARIOS = Object.freeze([
  'completed',
  'error',
  'aborted',
  'blocked',
  'max-tokens',
] as const)

/** The situations caused by the session waiting on the user, in settings order. */
export const PENDING_SCENARIOS = Object.freeze([
  'approval',
  'question',
  'plan-review',
] as const)

/** The one situation that belongs to no switch: the still-unanswered reminder. */
export const REMINDER_SCENARIO = 'reminder' as const

/** How many custom texts one situation may keep. */
export const TEXT_LIMIT_PER_SCENARIO = 3

/** Characters kept of one template's name (also the picker's label). */
export const TEXT_NAME_LIMIT = 24

/** Characters kept of one template's title (the host toast caps at 120). */
export const TEXT_TITLE_LIMIT = 120

/** Characters kept of one template's body (the host toast caps at 300). */
export const TEXT_BODY_LIMIT = 300

/** The id prefix the host gives a stored template. */
export const TEMPLATE_ID_PREFIX = 't_'

/** The shape of a stored template id. */
const TEMPLATE_ID = /^t_[a-z0-9]{4,}$/i

/** One user-saved popup text. */
export interface TextTemplate {
  /** Stable id, generated by the host; the settings store only this. */
  readonly id: string
  /** The label shown in the picker and the management list. */
  readonly name: string
  /** The title template, filled with placeholders at send time. */
  readonly title: string
  /** The body template, filled with placeholders at send time. */
  readonly body: string
  /** Host clock (ms) of the last save, for the management list. */
  readonly updatedAt: number
}

/** Every situation's saved templates. */
export type TextLibrary = Readonly<Record<NotifyScenario, readonly TextTemplate[]>>

/** A library with every situation empty. */
export function emptyTextLibrary(): TextLibrary {
  const library = {} as Record<NotifyScenario, readonly TextTemplate[]>
  for (const scenario of SCENARIO_IDS) library[scenario] = []
  return library
}

/** Whether a value is one stored template's id. */
export function isTemplateId(value: unknown): value is string {
  return typeof value === 'string' && TEMPLATE_ID.test(value)
}

/**
 * Find one situation's template by id.
 * @param library - the loaded library.
 * @param scenario - the situation it belongs to.
 * @param id - the settings' stored choice.
 * @returns the template, or undefined when it is gone.
 */
export function templateOf(
  library: TextLibrary,
  scenario: NotifyScenario,
  id: string | undefined,
): TextTemplate | undefined {
  if (id === undefined) return undefined
  return library[scenario].find(entry => entry.id === id)
}

/** A validated title/body pair, ready to store. */
export interface NormalizedTextDraft {
  readonly name: string
  readonly title: string
  readonly body: string
}

/** Why a draft was rejected. */
export type TextDraftProblem = 'name' | 'title' | 'body'

/** The result of validating one editor draft. */
export type TextDraftResult =
  | { readonly ok: true; readonly value: NormalizedTextDraft }
  | { readonly ok: false; readonly problem: TextDraftProblem }

/**
 * Validate one editor draft: trim every field, require each to be non-empty,
 * and bound the lengths to what the toast can actually show.
 * @param value - whatever the editor or an HTTP client sent.
 * @returns the normalized draft, or the first field that failed.
 */
export function normalizeTextDraft(value: unknown): TextDraftResult {
  const record = (value ?? {}) as { name?: unknown; title?: unknown; body?: unknown }
  const name = typeof record.name === 'string' ? record.name.trim() : ''
  const title = typeof record.title === 'string' ? record.title.trim() : ''
  const body = typeof record.body === 'string' ? record.body.trim() : ''
  if (name === '' || name.length > TEXT_NAME_LIMIT) return { ok: false, problem: 'name' }
  if (title === '' || title.length > TEXT_TITLE_LIMIT) return { ok: false, problem: 'title' }
  if (body === '' || body.length > TEXT_BODY_LIMIT) return { ok: false, problem: 'body' }
  return { ok: true, value: { name, title, body } }
}
